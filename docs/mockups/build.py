"""Renders the mockup pages from src/: screens.html and one page per area in screens/."""

from dataclasses import dataclass
from pathlib import Path

import sample_data as data
from jinja2 import Environment, FileSystemLoader, StrictUndefined
from markupsafe import Markup

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "src"
MARKER = "<!-- Generated by build.py from src/. Do not edit. -->"


@dataclass(frozen=True)
class Screen:
    id: str
    title: str
    caption: str
    body: Markup
    tickets: tuple[str, ...]


def environment():
    env = Environment(
        loader=FileSystemLoader(SOURCE),
        autoescape=True,
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    # Imported part files cannot see a template's variables, only globals.
    env.globals["data"] = data
    return env


def load_screen(env, path):
    name = path.relative_to(SOURCE).as_posix()
    module = env.get_template(name).make_module()
    missing = [key for key in ("screen_id", "title", "caption") if not hasattr(module, key)]
    if missing:
        raise ValueError(f"{name} does not set {', '.join(missing)}")
    body = Markup(str(module).strip())
    tickets = tuple(getattr(module, "tickets", ()))
    return Screen(module.screen_id, module.title, module.caption, body, tickets)


def load_areas(env):
    known = {slug for slug, _ in data.AREAS}
    folders = {path.name for path in (SOURCE / "areas").iterdir() if path.is_dir()}
    if unknown := folders - known:
        raise ValueError(f"src/areas has folders missing from AREAS: {sorted(unknown)}")
    built = {}
    for slug, _ in data.AREAS:
        paths = sorted((SOURCE / "areas" / slug).glob("*.html.j2"))
        if paths:
            built[slug] = [load_screen(env, path) for path in paths]
    return built


def render():
    """Returns every generated page as {path relative to the mockups folder: html}."""
    env = environment()
    built = load_areas(env)
    shared = {
        "marker": Markup(MARKER),
        "areas": data.AREAS,
        "built": built,
        "themes": data.THEMES,
        "default_theme": data.DEFAULT_THEME,
        "default_palette": data.DEFAULT_PALETTE,
    }
    pages = {
        "screens.html": env.get_template("index.html.j2").render(
            shared, root="", current="index", page_title="All screens"
        )
    }
    for slug, name in data.AREAS:
        if slug in built:
            pages[f"screens/{slug}.html"] = env.get_template("area.html.j2").render(
                shared, root="../", current=slug, page_title=name, screens=built[slug]
            )
    return pages


def main():
    for relative, html in render().items():
        target = ROOT / relative
        target.parent.mkdir(exist_ok=True)
        target.write_text(html, encoding="utf-8")
        print(f"wrote {relative}")


if __name__ == "__main__":
    main()
